#!/usr/bin/env python3
"""Regenerate package.json fish media + src/fish_table.inc from fish_catalog.csv."""

from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "fish_catalog.csv"
PACKAGE = ROOT / "package.json"
FISH_INC = ROOT / "src" / "fish_table.inc"

SCIENTIFIC_OVERRIDES: dict[str, str] = {
    "esox_indus.png": "Esox Indus",
    "anquilla_anquilla.png": "Anguilla rostrata",
    "rhinichtys_cataract.png": "Rhinichtys cataract\u00e6",
}


def load_rows() -> list[dict[str, str]]:
    with CATALOG.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def media_entry(name: str, path: str) -> dict:
    return {"type": "bitmap", "name": name, "file": path}


def main() -> None:
    rows = load_rows()
    media: list[dict] = [
        {
            "type": "bitmap",
            "name": "MENU_ICON",
            "file": "images/icon.png",
            "menuIcon": True,
        }
    ]
    inc_lines: list[str] = []

    for row in rows:
        filename = row["filename"]
        mono_name = row["resource"]
        color_name = f"FISH_COLOR_{mono_name[5:]}"
        media.append(media_entry(color_name, f"images/color/{filename}"))
        media.append(media_entry(mono_name, f"images/mono/{filename}"))
        scientific = SCIENTIFIC_OVERRIDES.get(
            filename, row["scientific"].replace('"', '\\"')
        )
        common = row["common"].replace('"', '\\"')
        inc_lines.append(
            f"  {{RESOURCE_ID_{color_name}, RESOURCE_ID_{mono_name}, "
            f'"{common}", "{scientific}"}},'
        )

    pkg = json.loads(PACKAGE.read_text(encoding="utf-8"))
    pkg["pebble"]["resources"]["media"] = media
    PACKAGE.write_text(json.dumps(pkg, indent=2) + "\n", encoding="utf-8")

    FISH_INC.write_text(
        "/* Generated by scripts/gen_fish_resources.py — do not edit by hand. */\n"
        "#ifndef FISH_TABLE_INC\n"
        "#define FISH_TABLE_INC\n"
        "static const Fish FISH[NUM_FISH] = {\n"
        + "\n".join(inc_lines)
        + "\n};\n"
        "#endif\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(rows)} fish × 2 to {PACKAGE.name} and {FISH_INC.name}")


if __name__ == "__main__":
    main()